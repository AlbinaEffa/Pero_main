/** Разбивает CSV-строку жанров проекта в массив (пустые/«Без жанра» отфильтровываются вызывающим). */
export function splitGenres(csv: string | null | undefined): string[] {
  if (!csv) return [];
  return csv.split(',').map(s => s.trim()).filter(Boolean);
}

/** Канонический формат хранения жанров проекта — CSV. */
export function joinGenres(genres: string[]): string {
  return genres.join(', ');
}
